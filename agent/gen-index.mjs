// Writes the generated indexes in agent/: symbols.md (every exported symbol with its file and line) and imports.md
// (which local module imports which). Run after changing src/: node agent/gen-index.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const SRC = join(ROOT, "src");
const OUT = join(ROOT, "agent");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return walk(path);
    return /\.(ts|tsx|mjs)$/.test(name) && !name.endsWith(".d.ts") ? [path] : [];
  });
}

const files = walk(SRC).sort();
const rel = (path) => relative(ROOT, path);

// Top-level exports: functions, classes, constants, types, and interfaces.
const EXPORT = /^export (?:default )?(?:async )?(function\*?|class|const|let|interface|type|enum) (\w+)/;

const symbolRows = [];
for (const file of files) {
  readFileSync(file, "utf8")
    .split("\n")
    .forEach((line, i) => {
      const match = EXPORT.exec(line);
      if (match) symbolRows.push(`| ${rel(file)} | ${i + 1} | ${match[1].replace("*", "")} | ${match[2]} |`);
    });
}

// Resolves a relative import to a file in src/. Handles the .js suffix used by NodeNext and the index.ts folder form.
function resolveImport(fromFile, spec) {
  const base = resolve(dirname(fromFile), spec);
  const candidates = [
    base.replace(/\.js$/, ".ts"),
    base.replace(/\.js$/, ".tsx"),
    base.replace(/\.js$/, ".mjs"),
    base + ".ts",
    base + ".tsx",
    base + ".mjs",
    join(base, "index.ts"),
    base,
  ];
  return candidates.find((candidate) => files.includes(candidate));
}

const IMPORT = /^import\s+(?:type\s+)?(?:[\s\S]*?\sfrom\s+)?["'](\.[^"']+)["'];?/gm;
const importedBy = new Map(files.map((file) => [file, []]));
const importsOf = new Map(files.map((file) => [file, []]));
for (const file of files) {
  for (const match of readFileSync(file, "utf8").matchAll(IMPORT)) {
    const target = resolveImport(file, match[1]);
    if (!target) continue;
    importsOf.get(file).push(target);
    importedBy.get(target).push(file);
  }
}

const importRows = files.map((file) => {
  const deps = [...new Set(importsOf.get(file))].map(rel).join(", ") || "-";
  const users = [...new Set(importedBy.get(file))].map(rel).join(", ") || "-";
  return `| ${rel(file)} | ${deps} | ${users} |`;
});

const header = "<!-- Generated by agent/gen-index.mjs. Do not edit by hand. -->";
writeFileSync(
  join(OUT, "symbols.md"),
  [header, "", "# Exported symbols", "", "| file | line | kind | name |", "| --- | --- | --- | --- |", ...symbolRows, ""].join("\n"),
);
writeFileSync(
  join(OUT, "imports.md"),
  [header, "", "# Module imports", "", "Each file, the local modules it imports, and the local modules that import it.", "", "| file | imports | imported by |", "| --- | --- | --- |", ...importRows, ""].join("\n"),
);
console.log(`symbols: ${symbolRows.length}, modules: ${files.length}`);
